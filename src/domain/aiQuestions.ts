/** מגריל `count` שאלות שונות מהמאגר (ללא חזרות), בלי השאלות שבקבוצת ההחרגה. */
export function pickQuestions(count: number, random: () => number = Math.random, exclude: readonly string[] = []): string[] {
  const pool = AI_QUESTION_BANK.filter((q) => !exclude.includes(q));
  const source = pool.length >= count ? pool : [...AI_QUESTION_BANK];
  const copy = [...source];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, count);
}
