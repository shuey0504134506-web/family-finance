function desktopContent(offline: boolean): HelpContent {
  return {
    faq: desktopFaq(offline),
    tips: TIPS.filter((i) => !PHONE_ONLY.has(i.id)).map(plain),
    savings: SAVINGS.map(plain),
  };
}

/** עזרה של תוכנת המחשב: תיאור המסכים והפעולות כפי שהם בתוכנה, ולפי סוג החשבון. */
export function DesktopHelp() {
  const ui = useUi();
  return <HelpScreen content={desktopContent(ui.me?.kind === 'offline')} />;
}
