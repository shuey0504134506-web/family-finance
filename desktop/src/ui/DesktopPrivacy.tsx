        <p>
          <strong>י. נ. ק.</strong>
          <br />
          טלפון:{' '}
          <a href={`tel:${PRIVACY_CONTACT_PHONE}`} dir="ltr">
            {PRIVACY_CONTACT_PHONE}
          </a>
        </p>
