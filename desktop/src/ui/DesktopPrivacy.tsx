import { ScreenHeader } from '../../../src/components/ScreenHeader';
import { PRIVACY_CONTACT_EMAIL, PRIVACY_CONTACT_PHONE } from '../../../src/config/appInfo';
import { ContactAdmin } from '../../../src/features/privacy/ContactAdmin';
import { usePrivacyLabel } from '../../../src/features/privacy/privacyLabel';
import { useUi } from './useController';

/**
 * מדיניות הפרטיות של תוכנת המחשב. הנוסח תלוי בסוג החשבון:
 * חשבון מנותק נשמר במחשב בלבד ואין בו שום קשר לשרת או למפעיל, ולכן גם אין בו פנייה למנהל.
 */
export function DesktopPrivacy() {
  const ui = useUi();
  const label = usePrivacyLabel();
  const kind = ui.phase === 'in' ? ui.me?.kind ?? null : null;
  return (
    <div className="app-shell">
      <ScreenHeader title={label} />
      <main>
        <DesktopPrivacyBody kind={kind} />
      </main>
    </div>
  );
}

/** גוף המדיניות. kind=null = עוד לא נכנסו לחשבון (מסך הכניסה), ואז מוצגים שני סוגי החשבון. */
export function DesktopPrivacyBody({ kind, showContactForm = true }: { showContactForm?: boolean; kind: 'online' | 'offline' | null }) {
  const offline = kind === 'offline';
  const online = kind === 'online';
  return (
      <div className="content prose">
        <p className="muted">
          {offline
            ? 'מדיניות זו מסבירה איך המידע נשמר בחשבון מנותק. גרסה 1.'
            : 'מדיניות זו מסבירה כיצד התוכנה אוספת, משתמשת ושומרת מידע. גרסה 1.'}
        </p>

        <p>
          מסירת פרטי החובה נעשית מרצונכם והיא תנאי לפתיחת חשבון מהסוג שבחרתם. פתיחת חשבון חדש מחייבת את אישור מדיניות הפרטיות.
        </p>
        {offline ? (
          <>
            <h2>חשבון מנותק: הכול נשאר במחשב הזה</h2>
            <ul>
              <li>כל הנתונים שאתה מזין (הכנסות, הוצאות, קטגוריות, תקציבים, חובות, משימות, רשימת קניות, מעשרות והגדרות) נשמרים בקובץ מקומי במחשב הזה בלבד.</li>
              <li>קובץ הנתונים מוצפן. הסיסמה או תשובות השחזור מאפשרות לפתוח אותו.</li>
              <li>התוכנה לא שולחת את הנתונים לשום שרת, לא מסנכרנת אותם ולא מתחברת ל-Firebase עבור חשבון כזה.</li>
              <li>מפעיל האפליקציה אינו מקבל שום מידע על החשבון: לא פרטי הרשמה, לא נתונים ולא סטטיסטיקות שימוש.</li>
              <li>פתיחת קובץ הנתונים מסתמכת על מפתח שנגזר מהסיסמה.</li>
            </ul>

            <h2>שחזור סיסמה</h2>
            <p>
              בחשבון מנותק אין אפשרות &quot;איפוס במייל&quot;. במקום זה יש שלוש שאלות שחזור, שחלקן שהגדרת וחלקן נגזרות מהפעולות האחרונות שלך. התשובות אינן נשמרות כטקסט גלוי,
              והן משמשות רק לפתיחת הקובץ אם שכחת את הסיסמה. מי ששוכח את הסיסמה וגם את התשובות לא יכול לשחזר את הנתונים, ואף אחד לא יכול לעזור לו בכך.
            </p>

            <h2>גיבוי ומחיקה</h2>
            <p>
              אין עותק בענן, ולכן כדאי להוריד גיבוי מלא מדי פעם (בהגדרות, בסעיף &quot;ניהול האפליקציה&quot;) ולשמור אותו במקום בטוח. מחיקת חשבון מנותק (בהגדרות, &quot;מחיקת חשבון&quot;) מוחקת את הקובץ במחשב
              לצמיתות, והיא בלתי הפיכה. מחיקת התוכנה בלבד אינה מוחקת את קובץ הנתונים.
            </p>
          </>
        ) : (
          <>
            {!online && <h2>שני סוגי חשבון</h2>}
            {!online && (
              <p>
                <strong>חשבון מנותק</strong> נשמר רק במחשב הזה, מוצפן בסיסמה, ולא מתחבר לשום שרת. <strong>חשבון מקוון</strong> שומר עותק מוצפן במחשב, ומסתנכרן עם הענן כשיש אינטרנט, כדי לעבוד גם
                באפליקציה ובאתר. פירוט על חשבון מנותק מופיע במדיניות הפרטיות כשנכנסים אליו.
              </p>
            )}
            <h2>איזה מידע נשמר</h2>
            <ul>
              <li>פרטי חשבון: שם פרטי, שם משפחה, שם העסק, כתובת מייל ומספר טלפון.</li>
              <li>הנתונים הפיננסיים שאתה מזין: הכנסות, הוצאות, קטגוריות, תקציבים, רישומי מעשרות, חובות, משימות והגדרות.</li>
              <li>במחשב עצמו נשמר עותק של הנתונים בקובץ מוצפן בסיסמה שלך, כדי שהתוכנה תעבוד גם בלי אינטרנט.</li>
              <li>הסיסמה אינה נשמרת בשום מקום. נשמרים רק הסימנים הדרושים לאימות שלה.</li>
            </ul>

            <h2>למה המידע משמש</h2>
            <p>
              אנו משתמשים במידע לניהול החשבון, לחישוב סיכומים, תקציב ומעשרות, לתמיכה ולסנכרון בין המחשב, האפליקציה והאתר.
            </p>
            <p>
              מפעיל האפליקציה רשאי לראות את פרטי ההרשמה של חשבון מקוון (שם, שם העסק, כתובת מייל ומספר טלפון), כדי לאשר חשבונות וליצור קשר, וכן מידע כללי ומצטבר: תאריך ההרשמה, מועד הכניסה האחרונה, מספר הפעולות
              ורמת השימוש. מסך הניהול מציג נתונים מצטברים ופרטי חשבון. גישה ישירה לתשתית הענן כפופה להרשאות הענן.
            </p>

            <h2>איפה המידע נשמר ואיך הוא מסונכרן</h2>
            <p>
              בחשבון מקוון הנתונים נשמרים גם בשירותי Firebase של Google (Firebase Authentication ו-Cloud Firestore). כל פעולה נשמרת קודם בקובץ המקומי, ומיד כשיש אינטרנט היא נשלחת לשרת. אם אין אינטרנט, היא ממתינה
              ונשלחת אוטומטית כשהחיבור חוזר, ופעולות שהוזנו במכשירים אחרים יורדות למחשב. כללי אבטחה בשרת מאפשרים לכל משתמש לקרוא ולשנות רק את הנתונים של עצמו, והתקשורת עם השרתים מוצפנת.
            </p>

            <h2>שימוש בתכונות בינה מלאכותית</h2>
            <p>
              אם בחרתם להשתמש ב־AI ואישרתם עיבוד אצל ספק חיצוני, השירות עשוי להעביר לספק הפעיל את השאלה,
              את הקשר השיחה ואת הנתונים הפיננסיים הדרושים למענה. האישור לכך נפרד מאישור מדיניות הפרטיות.
            </p>

            <h2>מחיקת חשבון ונתונים</h2>
            <p>
              ניתן למחוק את החשבון ואת כל הנתונים הכלולים בו במסך ההגדרות, בסעיף &quot;מחיקת חשבון&quot;. המחיקה בלתי הפיכה, ובחשבון מקוון היא כוללת גם את הנתונים בשרת. כמו כן ניתן להגיש בקשת מחיקה
              באמצעות פרטי יצירת הקשר שלהלן.
            </p>
          </>
        )}

        <p>קובצי ייצוא וגיבוי עשויים לכלול נתונים קריאים. מי שיש לו גישה לקובץ יכול לקרוא אותו. קבצים ששמרתם בנפרד נשארים בשליטתכם לאחר מחיקת החשבון.</p>

        <h2>יצירת קשר בנושא פרטיות</h2>
        <p>לכל פנייה, שאלה או בקשה בנושא פרטיות והגנה על מידע ניתן לפנות אל:</p>
        <p>
          <strong>י. נ. ק.</strong>
          <br />
          טלפון:{' '}
          <a href={`tel:${PRIVACY_CONTACT_PHONE}`} dir="ltr">
            {PRIVACY_CONTACT_PHONE}
          </a>
        </p>
        {PRIVACY_CONTACT_EMAIL && (
          <p>
            דואר אלקטרוני:{' '}
            <a href={`mailto:${PRIVACY_CONTACT_EMAIL}`} dir="ltr">
              {PRIVACY_CONTACT_EMAIL}
            </a>
          </p>
        )}

        <h2>זכויות יוצרים</h2>
        <p>
          כל הזכויות שמורות לעורכי האפליקציה. אין להעתיק, להפיץ, לשכפל, לשנות או לעשות שימוש מסחרי באפליקציה, בעיצובה או בתכניה, כולם או חלקם, ללא קבלת הסכמה מראש ובכתב.
        </p>

        {online && (
          <>
            <h2>פנייה למנהל האפליקציה</h2>
            <p>
              משתמש בחשבון מקוון יכול לשלוח הודעה ישירות למנהל האפליקציה, גם בנושאי פרטיות. ההודעה נקראת על ידי המנהל בלבד ונשמרת יחד עם כתובת האימייל של השולח, כדי שאפשר יהיה להשיב. התשובה מוצגת כאן.
              אם אין חיבור לאינטרנט, ההודעה נשמרת ונשלחת אוטומטית כשהחיבור חוזר.
            </p>
            {showContactForm && <ContactAdmin />}
          </>
        )}
      </div>
  );
}
